SCIENTIFIC_MATERIALS_DB.forEach(m => {
  SCIENTIFIC_MAP.set(m.name.toLowerCase().trim(), m);
  if (m.cas && m.cas !== 'Mixture') {
    SCIENTIFIC_MAP.set(m.cas.trim(), m);
  }
});

export function getAllScientificMaterials(): KineticFragranceMaterial[] {
  return [...SCIENTIFIC_MATERIALS_DB];
}

export function findScientificMaterial(query: string): KineticFragranceMaterial | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  if (SCIENTIFIC_MAP.has(q)) {
    return SCIENTIFIC_MAP.get(q);
  }
  return SCIENTIFIC_MATERIALS_DB.find(m => 
    m.name.toLowerCase() === q ||
    m.cas === query.trim() ||
    m.name.toLowerCase().includes(q) ||
    (m.nameAr && m.nameAr.includes(query.trim()))
  );
}

